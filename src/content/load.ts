    [artRoom.id]: artRoom,
    [mist.id]: mist,
    [enchanted.id]: enchanted,
    [hills.id]: hills,
    [sanctuary.id]: sanctuary,
    [cavern.id]: cavern,
    [cafe.id]: cafe,
    [market.id]: market,
    [parlor.id]: parlor,
    [sueCottage.id]: sueCottage,
