function stepBass(
  bars: readonly (readonly [first: number, second: number])[],
  stepsPerBar: number,
  secondOffset: number,
  dur1: number,
  dur2: number,
  vel1 = 0.62,
  vel2 = 0.5,
): NoteEvent[] {
  const out: NoteEvent[] = [];
  bars.forEach(([first, second], bar) => {
    const base = bar * stepsPerBar;
    const isLast = bar === bars.length - 1;
    if (isLast && second === first) {
      out.push([base, first, stepsPerBar - 2, vel1 + 0.02]);
    } else {
      out.push([base, first, dur1, vel1]);
      out.push([base + secondOffset, second, dur2, vel2]);
    }
  });
  return out;
}

function fiestaStrum(bars: readonly (readonly number[])[]): NoteEvent[] {
  const out: NoteEvent[] = [];
  bars.forEach((triad, bar) => {
    const base = bar * 16;
    out.push(...chord(base + 2, triad, 1.8, 0.46));
    out.push(...chord(base + 6, triad, 2.2, 0.52));
    out.push(...chord(base + 10, triad, 1.8, 0.48));
    out.push(...chord(base + 14, triad, 1.6, 0.5));
  });
  return out;
}

function fiestaBass(
  bars: readonly (readonly [root: number, fifth: number, lead: number])[],
): NoteEvent[] {
  const out: NoteEvent[] = [];
  bars.forEach(([root, fifth, lead], bar) => {
    const base = bar * 16;
    out.push([base, root, 3.5, 0.68]);
    out.push([base + 6, fifth, 3.5, 0.58]);
    out.push([base + 12, lead, 3, 0.62]);
  });
  return out;
}

