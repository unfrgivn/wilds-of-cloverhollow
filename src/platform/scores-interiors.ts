function ragStride(
  bars: readonly (readonly [
    root1: number,
    root3: number,
    chord2: readonly number[],
    chord4: readonly number[],
  ])[],
): NoteEvent[] {
  const out: NoteEvent[] = [];
  bars.forEach(([root1, root3, chord2, chord4], bar) => {
    const base = bar * 16;
    out.push([base, root1, 3, 0.6]);
    out.push(...chord(base + 4, chord2, 2.5, 0.54));
    out.push([base + 8, root3, 3, 0.56]);
    out.push(...chord(base + 12, chord4, 2.5, 0.52));
  });
  return out;
}

